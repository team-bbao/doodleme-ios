/// 카드를 고르는 중일 때, 고른 것을 **무엇에 쓸지**.
///
/// 고르는 화면은 하나인데 끝에 하는 일이 둘이다.
/// 하단 바의 마지막 버튼이 이것에 따라 「삭제」가 되거나 「내보내기」가 된다.
///
/// 두 일을 한 모드에 몰아 버튼을 둘 다 세우면
/// 취소·개수·삭제·내보내기 네 개가 서서 무엇을 하려던 참인지 알기 어려워진다.
/// 들어온 길이 다르므로(카드 꾹 누르기 / 상단 􀈂) 무엇을 하려는지는 이미 정해져 있다.
enum GallerySelectionPurpose {
    /// 카드를 꾹 눌러 들어왔다. 고른 것을 지운다.
    case delete
    /// 상단 공유 버튼으로 들어왔다. 고른 것을 카드로 만들어 내보낸다.
    case export
}
